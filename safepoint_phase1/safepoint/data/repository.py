"""Data-access contract for the UI. `SqliteRepository` (safepoint/db) is the implementation."""
from __future__ import annotations

from typing import Protocol

from .models import ActivityEntry, ChangedFile, MissingFile, Project, Snapshot, TreeNode


class BackupRepository(Protocol):
    def get_projects(self) -> list[Project]: ...
    def get_snapshots(self) -> list[Snapshot]: ...
    def get_changed_files(self, snapshot_id: str) -> list[ChangedFile]: ...
    def get_restore_tree(self, snapshot_id: str) -> tuple[TreeNode, ...]: ...
    def get_missing_files(self) -> list[MissingFile]: ...
    def get_activity(self) -> list[ActivityEntry]: ...
    def get_settings(self) -> dict: ...
